const norm = (s) => String(s || '').toLowerCase().replace(/\s+/g, '')

function sectionText(s) {
  return [s.title, s.summary, ...(s.steps || []), ...(s.notes || []), ...((s.table?.rows || []).flat())].join(' ')
}

/** หัวข้อคู่มือที่ role นี้เห็น จัดเป็นกลุ่ม (ตัดกลุ่มว่าง) · query = ค้นทุกคำในหัวข้อ/ขั้นตอน (AND) */
export function manualFor(role, query = '') {
  const words = String(query || '').trim().split(/\s+/).map(norm).filter(Boolean)
  const visible = MANUAL_SECTIONS.filter(s => s.roles.includes(role))
    .filter(s => !words.length || words.every(w => norm(sectionText(s)).includes(w)))
  return MANUAL_GROUPS
    .map(g => ({ ...g, sections: visible.filter(s => s.group === g.key) }))
    .filter(g => g.sections.length)
}
